# -*- coding: utf-8 -*-
"""生成全部启动脚本（纯 ASCII + CRLF）。

脚本自动定位项目根目录（脚本所在目录的上一级），
不再硬编码本机路径，换电脑/换文件夹都能用。

用法：python tools/make_launcher.py
生成：scripts/launch_window.ps1  scripts/launch_silent.ps1  scripts/stop.ps1
"""
import os

APP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(APP_DIR, "scripts")

COMMON = r"""# Shuye launcher - auto-generated by tools/make_launcher.py
# Locates the project root from this script's own location.

$AppDir = Split-Path -Parent $PSScriptRoot
$Url = "http://127.0.0.1:7860"
$Port = 7860

function Test-Port([int]$p) {
    try {
        $c = New-Object System.Net.Sockets.TcpClient
        $c.Connect("127.0.0.1", $p)
        $c.Close()
        return $true
    } catch {
        return $false
    }
}

function Find-Python {
    # 1) project-local runtimes first, so the app travels with its own python
    $local = @(
        (Join-Path $AppDir "portable\python\python.exe"),
        (Join-Path $AppDir "python.exe")
    )
    foreach ($p in $local) {
        if (Test-Path $p) { return $p }
    }
    # 2) then the system python
    $c = Get-Command python -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    $c = Get-Command py -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    $roots = @(
        (Join-Path $env:LOCALAPPDATA "Programs\Python"),
        (Join-Path $env:ProgramFiles "Python")
    )
    foreach ($r in $roots) {
        if (Test-Path $r) {
            $hit = Get-ChildItem $r -Directory -Filter "Python3*" -ErrorAction SilentlyContinue |
                Sort-Object Name -Descending |
                ForEach-Object { Join-Path $_.FullName "python.exe" } |
                Where-Object { Test-Path $_ } |
                Select-Object -First 1
            if ($hit) { return $hit }
        }
    }
    return $null
}
"""

NO_PY = r"""
if (-not $py) {
    Write-Host "Python not found." -ForegroundColor Red
    Write-Host "Install Python 3.10+ from https://www.python.org/downloads/ and tick 'Add python.exe to PATH'."
    Read-Host "Press Enter to close"
    exit 1
}
"""

WINDOW = COMMON + r"""
if (Test-Port $Port) {
    Write-Host "Already running. Opening browser..."
    Start-Process $Url
    exit 0
}

$py = Find-Python
""" + NO_PY + r"""
$env:PYTHONIOENCODING = "utf-8"
Write-Host "Shuye is starting ..." -ForegroundColor Green
Write-Host ("Python : " + $py) -ForegroundColor DarkGray
Write-Host ("Folder : " + $AppDir) -ForegroundColor DarkGray
Write-Host ("Open   : " + $Url) -ForegroundColor Green
Write-Host "Keep this window open. Close it or press Ctrl+C to stop." -ForegroundColor DarkGray
Write-Host ""

Start-Process $Url
Set-Location $AppDir
& $py "server.py" $Port
"""

SILENT = COMMON + r"""
if (Test-Port $Port) {
    Start-Process $Url
    exit 0
}

$py = Find-Python
""" + NO_PY + r"""
$env:PYTHONIOENCODING = "utf-8"
$psi = New-Object System.Diagnostics.ProcessStartInfo
$psi.FileName = $py
$psi.Arguments = "server.py " + $Port
$psi.WorkingDirectory = $AppDir
$psi.UseShellExecute = $true
$psi.WindowStyle = "Minimized"
[System.Diagnostics.Process]::Start($psi) | Out-Null

for ($i = 0; $i -lt 80; $i++) {
    Start-Sleep -Milliseconds 500
    if (Test-Port $Port) { break }
}

if (-not (Test-Port $Port)) {
    Write-Host "Server failed to start." -ForegroundColor Red
    Write-Host "Check that port 7860 is free, or run launch_window.ps1 to see the error."
    Read-Host "Press Enter to close"
    exit 1
}

Start-Process $Url
"""

STOP = r"""# Shuye stop - auto-generated by tools/make_launcher.py
$AppDir = Split-Path -Parent $PSScriptRoot
$stopped = 0
Get-CimInstance Win32_Process -Filter "Name='python.exe'" -ErrorAction SilentlyContinue |
    Where-Object { $_.CommandLine -like "*server.py*" } |
    ForEach-Object {
        try {
            Stop-Process -Id $_.ProcessId -Force
            $stopped++
        } catch { }
    }
if ($stopped -gt 0) {
    Write-Host ("Stopped " + $stopped + " server process(es).")
} else {
    Write-Host "No running server found."
}
Start-Sleep -Seconds 1
"""


def write(name, text):
    path = os.path.join(SCRIPTS, name)
    with open(path, "wb") as f:
        f.write(text.replace("\n", "\r\n").encode("ascii"))
    print("written:", os.path.join("scripts", name))


if __name__ == "__main__":
    os.makedirs(SCRIPTS, exist_ok=True)
    write("launch_window.ps1", WINDOW)
    write("launch_silent.ps1", SILENT)
    write("stop.ps1", STOP)
