# -*- coding: utf-8 -*-
"""生成桌面快捷方式（通过生成纯 ASCII 的 PS 脚本再执行，避免中文编码问题）。

桌面文件：
  书页.lnk              启动（静默，自动开浏览器）
  书页（关闭服务）.lnk   停止
用法：python tools/make_shortcuts.py
"""
import os
import subprocess

APP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PS1 = os.path.join(APP_DIR, "scripts", "make_shortcuts.ps1")

BODY = r"""# Shuye desktop shortcuts - auto-generated by tools/make_shortcuts.py
# Uses $PSScriptRoot so it works wherever the project lives.
$AppDir = Split-Path -Parent $PSScriptRoot
$Desktop = [Environment]::GetFolderPath("Desktop")
$ShiYe = [string][char]0x4E66 + [char]0x9875
$Close = [char]0xFF08 + [char]0x5173 + [char]0x95ED + [char]0x670D + [char]0x52A1 + [char]0xFF09
$ws = New-Object -ComObject WScript.Shell

$s1 = $ws.CreateShortcut((Join-Path $Desktop ($ShiYe + ".lnk")))
$s1.TargetPath = "powershell.exe"
$s1.Arguments = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + (Join-Path $AppDir "scripts\launch_silent.ps1") + '"'
$s1.WorkingDirectory = $AppDir
$s1.IconLocation = "C:\Windows\System32\shell32.dll,2"
$s1.Description = "Shuye - start"
$s1.Save()

$s2 = $ws.CreateShortcut((Join-Path $Desktop ($ShiYe + $Close + ".lnk")))
$s2.TargetPath = "powershell.exe"
$s2.Arguments = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + (Join-Path $AppDir "scripts\stop.ps1") + '"'
$s2.WorkingDirectory = $AppDir
$s2.IconLocation = "C:\Windows\System32\shell32.dll,27"
$s2.Description = "Shuye - stop"
$s2.Save()

Write-Host "shortcuts written to" $Desktop
"""


def main():
    os.makedirs(os.path.join(APP_DIR, "scripts"), exist_ok=True)
    with open(PS1, "wb") as f:
        f.write(BODY.replace("\n", "\r\n").encode("ascii"))
    print("written:", os.path.relpath(PS1, APP_DIR))
    r = subprocess.run(
        ["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", PS1],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = (r.stdout or "").strip()
    err = (r.stderr or "").strip()
    if out:
        print(out)
    if err:
        print("ERR:", err[:500])


if __name__ == "__main__":
    main()
